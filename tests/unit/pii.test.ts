import { describe, it, expect } from 'vitest'
import { pseudonymize } from '@/lib/ai-protocol'
import { scrubPd, containsPatientPd, nameStem } from '@/lib/pii'

// Все ФИО, адреса и телефоны — вымышленные
const P = ['Иванов', 'Пётр', 'Сергеевич']

describe('pseudonymize: склонения и прочие ПДн (чек-лист P0 ИИ)', () => {
  it('«Иванову Петру Сергеевичу» и «у Иванова жалобы» — имён не остаётся', () => {
    const a = pseudonymize('Направление выдано Иванову Петру Сергеевичу.', P)
    const b = pseudonymize('у Иванова жалобы на боль', P)
    for (const t of [a, b]) expect(t).not.toMatch(/Иванов|Пётр|Петр|Сергеевич/i)
    expect(b).toContain('жалобы на боль')
  })

  it('все падежи фамилии, имени, отчества', () => {
    const forms = 'Иванов, Иванова, Иванову, Ивановым, Иванове; Пётр, Петра, Петру, Петром, Петре; Сергеевич, Сергеевича, Сергеевичу, Сергеевичем'
    const out = pseudonymize(forms, P)
    expect(out).not.toMatch(/Иванов|Пётр|Петр|Сергеевич/i)
  })

  it('женские формы и беглая гласная', () => {
    expect(pseudonymize('Смирновой Анне Павловне, у Смирновой', ['Смирнова', 'Анна', 'Павловна'])).not.toMatch(/Смирнов|Анн|Павловн/i)
    expect(pseudonymize('вызвали Павла', ['Козлов', 'Павел'])).not.toMatch(/Павл/i)
    expect(pseudonymize('Карине Мариевне и Марии', ['Карина', 'Мария'])).not.toMatch(/Карин|Мари/i)
  })

  it('родственники, ФИО с отчеством и инициалы', () => {
    const t = pseudonymize('Со слов мать: Кузнецова Ольга. Сопровождает муж Сидоров. Звонил Николай Андреевич; осмотр Петренко В.А.', P)
    expect(t).not.toMatch(/Кузнецов|Ольга|Сидоров|Николай|Андреевич|Петренко/)
    expect(t).toContain('мать: [родственник]')
  })

  it('адреса и организации', () => {
    const t = pseudonymize('Проживает: 123456, г. Москва, ул. Садовая-Кудринская, д. 15, кв. 7. Работает в ООО «Ромашка-Плюс», ранее ГБУЗ Городская Больница, ребёнок ходит в школа № 1234, работает на «Заводе Вымпел».', P)
    expect(t).not.toMatch(/Москва|Садовая|15, кв|кв\. 7|Ромашка|Городская Больница|1234|Вымпел|123456/)
    expect(t).toContain('[адрес]')
    expect(t).toContain('[организация]')
  })

  it('телефон пациента в любом формате, e-mail, СНИЛС, полис', () => {
    const t = scrubPd('тел. 8 (900) 111-22-33, 9001112233, +79001112233, mail test.patient@example.com, СНИЛС 123-456-789 01, полис 1234567890123456', { phones: ['+79001112233'] })
    expect(t).not.toMatch(/111|9001112233|example\.com|123-456|1234567890123456/)
  })

  it('медицинский текст не портится', () => {
    const med = 'Жалобы на боль при накусывании, кариес K02.1. Объективно: слизистая без особенностей. Назначен Ибупрофен 400 мг. План: пломба.'
    expect(pseudonymize(med, P)).toBe(med)
    const tricky = 'В анамнезе ОРВИ. Аллергия на пенициллин. Ребёнок ходит в сад, мать здорова. Болезнь Боткина в детстве.'
    expect(pseudonymize(tricky, P)).toBe(tricky)
  })

  it('containsPatientPd находит падежную форму и телефон без форматирования', () => {
    const o = { names: P, phones: ['+7 900 111-22-33'] }
    expect(containsPatientPd('звонили Иванову', o)).toBe(true)
    expect(containsPatientPd('79001112233', o)).toBe(true)
    expect(containsPatientPd('без данных', o)).toBe(false)
  })

  it('nameStem даёт основу для склонений', () => {
    expect(nameStem('Иванову')).toContain('Иванов')
    expect(nameStem('Мария')).toContain('Мари')
  })
})
